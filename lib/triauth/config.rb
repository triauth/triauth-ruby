module Triauth
  class << self
    # The global triauth-ruby configuration, exposed as `Triauth.config` and shared by reference with every internal module.
    # Each API method also takes a per-call override Hash as its last argument, and an unknown key in either place is
    # rejected with the error `invalid_config`. The `logger` and `resolver` defaults are filled in by the entry module.
    # The global `config` Hash should not be mutated while API calls are in flight.
    #
    # @return [Hash{Symbol => Object}] the configuration Hash, with the entries
    #   `requireSecure` (Boolean),
    #   `resolver` (Object, nil),
    #   `logger` (Object, nil),
    #   `randomSource` (Proc, nil),
    #   `maximalAllowedClientClockDrift` (Integer),
    #   `maximalAllowedServerClockDrift` (Integer),
    #   `authTimeout` (Integer),
    #   `pingTimeout` (Integer),
    #   `attestTimeout` (Integer),
    #   `signTimeout` (Integer),
    #   `stampTimeout` (Integer),
    #   `cid` (String, false, nil)
    attr_reader :config
  end

  @config = {
    # When true, all challenge-response API methods (authenticate, ping, attest, sign, stamp), Triauth.check,
    # and Triauth.verify require a successful result to be DNSSEC-secure: any otherwise-valid response that was
    # not reported DNSSEC-validated (`secure !== true`) is rejected with the error `dnssec_required` ("Your domain does not
    # support DNSSEC, which is required to continue."). Leave false (default) to inspect the `secure` property yourself and stay
    # interoperable with non-DNSSEC domains; set true for mission-critical systems that demand strict
    # cryptographic assurance.
    requireSecure: false,

    resolver: nil,
    logger: nil,

    # Source of cryptographic randomness used to generate challenge nonces. Must be a callable that
    # receives a byte count and returns a binary String of exactly that many bytes (same shape as `SecureRandom.random_bytes`).
    # Leave as nil to use `SecureRandom.random_bytes` (default). You may
    # override this with a higher-entropy or hardware-backed RNG, or - in test scenarios - with
    # a deterministic byte stream to make nonces reproducible.
    randomSource: nil,

    # The maximal allowed clock drift between the current clock (e.g., server time), and the end-user's clock (as seen by the web browser and Triauth Authenticator app),
    # including network round-trip time and any request pre-processing delays.
    # Applied when checking timestamps generated by the user's device (e.g., the `ts` embedded in signatures).
    maximalAllowedClientClockDrift: 30 * 1000,

    # The maximal allowed clock drift between your own servers - e.g., when, due to load balancing, a challenge
    # is generated (stage 1) and verified (stage 3) by two different hosts with imperfectly synchronized clocks.
    # Applied when checking timestamps generated by your own servers (the challenge `iat` freshness window).
    # Keep it small: well-managed (NTP-synchronized) fleets stay within milliseconds of each other.
    maximalAllowedServerClockDrift: 5 * 1000,

    # Timeout for the user to approve the request before it is considered expired (basing on challenge `iat` time, widened by `maximalAllowedServerClockDrift`).
    authTimeout: 3 * 60_000,
    pingTimeout: 15_000,
    attestTimeout: 15 * 60_000,
    signTimeout: 30 * 60_000,
    stampTimeout: 15_000,

    # The correlation id, emitted by the logger to trace related log entries across the system. Three modes:
    #   - nil    (default): "autofill" - the logger mints a fresh id for each API call (shown as `[cid:...]`).
    #   - false:            explicit opt-out - no `[cid:...]` tag is emitted.
    #   - string:           use this exact id for the call.
    cid: nil
  }

  # Frozen snapshot of the recognized `Triauth.config` keys, captured at module load.
  #
  # The public API methods use this to reject config overrides that carry an unknown key (error `invalid_config`).
  #
  # @return [Array<Symbol>] frozen
  KNOWN_CONFIG_KEYS = config.keys.freeze
end
